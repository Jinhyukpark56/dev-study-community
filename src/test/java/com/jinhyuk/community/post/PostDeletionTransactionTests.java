package com.jinhyuk.community.post;

import com.jinhyuk.community.comment.Comment;
import com.jinhyuk.community.comment.CommentRepository;
import com.jinhyuk.community.user.User;
import com.jinhyuk.community.user.UserRepository;
import com.jinhyuk.community.user.UserService;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

@SpringBootTest
class PostDeletionTransactionTests {

    @Autowired
    private PostService postService;

    @Autowired
    private PostRepository postRepository;

    @Autowired
    private CommentRepository commentRepository;

    @Autowired
    private UserRepository userRepository;

    @Autowired
    private UserService userService;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    private User author;
    private Post post;
    private Comment comment;

    @BeforeEach
    void setUp() {
        dropDeleteBlockerTable();
        commentRepository.deleteAll();
        postRepository.deleteAll();
        userRepository.deleteAll();

        assertTrue(userService.register("delete-author@example.com", "correct-password"));
        author = userRepository.findByEmail("delete-author@example.com").orElseThrow();
        post = postRepository.save(new Post("삭제 transaction", "댓글과 함께 삭제", author));
        comment = commentRepository.save(new Comment("함께 삭제할 댓글", post, author));
    }

    @AfterEach
    void cleanUp() {
        dropDeleteBlockerTable();
        commentRepository.deleteAll();
        postRepository.deleteAll();
        userRepository.deleteAll();
    }

    @Test
    void deletesCommentsBeforePostInOneTransaction() {
        assertEquals(PostOperationResult.SUCCESS, postService.deletePost(post.getId(), author));

        assertFalse(commentRepository.existsById(comment.getId()));
        assertFalse(postRepository.existsById(post.getId()));
        assertTrue(userRepository.existsById(author.getId()));
    }

    @Test
    void restoresDeletedCommentsWhenPostDeletionFails() {
        jdbcTemplate.execute("""
                create table post_delete_blocker (
                    id bigint generated by default as identity primary key,
                    post_id bigint not null,
                    constraint fk_post_delete_blocker
                        foreign key (post_id) references post(id)
                )
                """);
        jdbcTemplate.update(
                "insert into post_delete_blocker (post_id) values (?)",
                post.getId());

        assertThrows(
                DataIntegrityViolationException.class,
                () -> postService.deletePost(post.getId(), author));

        assertTrue(postRepository.existsById(post.getId()));
        assertTrue(commentRepository.existsById(comment.getId()));
    }

    private void dropDeleteBlockerTable() {
        jdbcTemplate.execute("drop table if exists post_delete_blocker");
    }
}
